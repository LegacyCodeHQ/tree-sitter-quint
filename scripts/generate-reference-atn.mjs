// Generate the scanner's recognition tables from the exact reference release.
import assert from 'node:assert/strict';
import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const cli = realpathSync(process.env.QUINT_CLI ?? join(root,
  'test/reference-quint033/node_modules/@informalsystems/quint/dist/src/cli.js'));
const version = JSON.parse(readFileSync(join(dirname(cli), '../../package.json'), 'utf8')).version;
assert.equal(version, '0.33.0', `Recognition tables require Quint 0.33.0; found ${version}`);
const require = createRequire(cli);
const { CharStreams, CommonTokenStream } = require('antlr4ts');
const { QuintLexer } = require(join(dirname(cli), 'generated/QuintLexer.js'));
const { QuintParser } = require(join(dirname(cli), 'generated/QuintParser.js'));
const parser = new QuintParser(new CommonTokenStream(new QuintLexer(CharStreams.fromString(''))));
const atn = parser.atn;
assert.equal(atn.maxTokenType, 71);
assert(atn.states.length < 65536);
assert.equal(parser.ruleNames[3], 'declaration');
assert.equal(parser.ruleNames[4], 'operDef');
const lines = [
  '/* Generated by scripts/generate-reference-atn.mjs from Quint 0.33.0. See NOTICE. */',
  '#ifndef QUINT_033_ATN_H', '#define QUINT_033_ATN_H', '#include <stdint.h>',
  'typedef struct { uint16_t first; uint8_t count, stop; } QState;',
  'typedef struct { uint16_t target, follow; uint8_t kind, rule, precedence; uint64_t low; uint16_t high; } QTransition;',
  'static const QState q_states[] = {',
];
let offset = 0;
for (const state of atn.states) {
  const count = state?.transitions.length ?? 0;
  assert(count < 256 && offset < 65536);
  lines.push(`{${offset},${count},${state?.stateType === 7 ? 1 : 0}},`);
  offset += count;
}
lines.push('};', 'static const QTransition q_transitions[] = {');
for (const state of atn.states) {
  for (const transition of state?.transitions ?? []) {
    // No custom predicates occur in this release. Actions report diagnostics
    // or construct the frontend AST; they do not change recognition.
    assert([1, 2, 3, 5, 6, 7, 8, 9, 10].includes(transition.serializationType));
    assert((transition.precedence ?? 0) < 256);
    let mask = 0n;
    for (let token = -1; token <= atn.maxTokenType; token++) {
      if (transition.matches(token, 1, atn.maxTokenType)) mask |= 1n << BigInt(token + 1);
    }
    const low = (mask & ((1n << 64n) - 1n)).toString(16);
    const high = (mask >> 64n).toString(16);
    lines.push(`{${transition.target.stateNumber},${transition.followState?.stateNumber ?? 0},`
      + `${transition.serializationType},${transition.ruleIndex ?? 0},${transition.precedence ?? 0},`
      + `UINT64_C(0x${low}),0x${high}},`);
  }
}
lines.push('};', `static const uint16_t q_rules[] = {${atn.ruleToStartState.map(s => s.stateNumber).join(',')}};`,
  'typedef struct { const char *text; uint8_t kind; } QLiteral;',
  'static const QLiteral q_literals[] = {');
for (let token = 1; token <= atn.maxTokenType; token++) {
  const literal = parser.vocabulary.getLiteralName(token);
  if (literal) lines.push(`{${JSON.stringify(literal.slice(1, -1))},${token}},`);
}
lines.push('};', '#endif', '');
const contents = lines.join('\n');
const output = join(root, 'src/quint_033_atn.h');
if (process.argv.includes('--check')) {
  assert.equal(readFileSync(output, 'utf8'), contents, 'Reference tables are stale; run bun run generate:reference');
} else {
  writeFileSync(output, contents);
}
console.log(`Quint ${version} recognition tables ${process.argv.includes('--check') ? 'verified' : 'generated'}`);
